        <h1 id="authenticating-requests">Authenticating requests</h1>
<p>To authenticate requests, include an <strong><code>Authorization</code></strong> header with the value <strong><code>"Bearer {YOUR_AUTH_KEY}"</code></strong>.</p>
<p>All authenticated endpoints are marked with a <code>requires authentication</code> badge in the documentation below.</p>
<p>You can retrieve your token by visiting your dashboard and clicking <b>Generate API token</b>.</p>

        <h1 id="core-auth">Core / Auth</h1>

    

                                <h2 id="core-auth-POSTapi-v1-core-auth-register">Register</h2>

<p>
<small class="badge badge-darkred">requires authentication</small>
</p>

<p>Create an account with a mobile number or email address (at least one is required).
Issues a verification code to whichever identifier was provided and returns an API token
immediately — the account can authenticate right away, but protected endpoints stay
gated behind <code>account.verified</code> until the code is confirmed via POST .../auth/verify.</p>

<span id="example-requests-POSTapi-v1-core-auth-register">
<blockquote>Example request:</blockquote>


<div class="bash-example">
    <pre><code class="language-bash">curl --request POST \
    "http://localhost/api/v1/core/auth/register" \
    --header "Authorization: Bearer {YOUR_AUTH_KEY}" \
    --header "Content-Type: application/json" \
    --header "Accept: application/json" \
    --data "{
    \"name\": \"Ahmed Al-Otaibi\",
    \"email\": \"ahmed@example.com\",
    \"mobile\": \"+966501234567\",
    \"password\": \"Secr3tPass\",
    \"terms_accepted\": true,
    \"password_confirmation\": \"Secr3tPass\"
}"
</code></pre></div>


<div class="javascript-example">
